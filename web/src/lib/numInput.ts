// 숫자 칸 입력 정리 (출시 전 수정 B5, docs/plan-2026-10-16-prelaunch-fixes.md)
// 부호·소수는 그대로 두고, 천 단위 쉼표와 숫자 뒤에 붙은 단위 글자만 뗀다. 값을 조용히 다른 값으로 바꾸지 않는다.
//   '-1' · '−1' → '-1' (양수로 바꾸지 않음 → 범위 검사에서 안내)
//   '14.8' · '0.9' → 그대로
//   '108 mg/dL' → '108'
//   '1,200' → '1200'
//   '132/84' 처럼 숫자가 둘 이상이면 그대로 둔다 → 숫자가 아니라서 형식·범위 안내가 뜬다

export function cleanNum(raw: string): string {
  const s = raw.replace(/[−–—]/g, '-').trim().replace(/(\d),(?=\d{3}(?!\d))/g, '$1');
  const m = /^(-?\d*(?:\.\d*)?)\s*([^\d]*)$/.exec(s);
  return m ? m[1] : s;
}
